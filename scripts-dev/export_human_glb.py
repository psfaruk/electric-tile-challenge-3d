#!/usr/bin/env python3
"""Blender headless pipeline: normalize the Quaternius CC0 'Male_Casual'
character and export a game-ready GLB with all animations + PBR micro-detail
textures baked in (albedo tints generated by gen_textures_human.py).

Run (Blender 3.6+):
  ./blender --background --python scripts-dev/export_human_glb.py -- \
      <source.blend> <character_textures_dir> <out.glb>

Pipeline steps:
  1. open blend, drop stale zero-size image datablocks
  2. drop actions authored for a different rig (missing bones)
  3. normalize authored height (~4.83 m) to 1.80 m — bake scale into
     armature + mesh, shrink pose .location fcurves to match
  4. rebuild every material as Principled BSDF with:
       - baked tinted albedo (sRGB, base color factor stays white)
       - tangent-space normal map (Non-Color) per body part
       - tuned roughness (skin/fabric/leather/hair)
  5. wire every compatible action as a 1-strip NLA track (ACTIONS export mode)
  6. export GLB (Y-up, embedded textures, skins, animations)
"""
import bpy
import sys

argv = sys.argv[sys.argv.index("--") + 1:]
SRC = argv[0]
TEX = argv[1]
OUT = argv[2]
TARGET_HEIGHT = 1.8

# material -> (roughness, normal texture or None); albedo comes from
# TEX/tinted/<Material>_albedo.png (see gen_textures_human.py BLEND_COLORS)
ROUGHNESS = {
    "Skin": 0.55, "Eyes": 0.25, "Hair": 0.65,
    "Shirt": 0.85, "Pants": 0.85, "Socks": 0.85, "Shoes": 0.45,
}
NORMALS = {
    "Skin": "skin_detail_normal.png", "Hair": "hair_strand_normal.png",
    "Shirt": "fabric_weave_normal.png", "Pants": "fabric_weave_normal.png",
    "Socks": "fabric_weave_normal.png", "Shoes": "leather_shoe_normal.png",
    # Eyes: plain color only
}

bpy.ops.wm.open_mainfile(filepath=SRC)

arm = bpy.data.objects["HumanArmature"]
mesh_ob = bpy.data.objects["BaseHuman"]
arm.data.pose_position = 'REST'

# ---- 1. drop stale zero-size image datablocks -----------------------------------
for img in list(bpy.data.images):
    if img.size[0] == 0 or img.size[1] == 0:
        try:
            bpy.data.images.remove(img, do_unlink=True)
        except Exception:
            pass
print("STALE IMAGES PURGED")

# ---- 2. drop incompatible actions -----------------------------------------------
bone_names = set(b.name for b in arm.data.bones)
removed = []
for act in list(bpy.data.actions):
    targets = set()
    for fc in act.fcurves:
        if 'pose.bones' in fc.data_path:
            targets.add(fc.data_path.split('"')[1])
    if targets - bone_names:
        removed.append(act.name)
        bpy.data.actions.remove(act)
print("REMOVED INCOMPATIBLE:", removed)

# ---- 3. height normalization ------------------------------------------------------
raw_height = max(abs(mesh_ob.dimensions.z), 1e-9)
S = TARGET_HEIGHT / raw_height
print(f"raw height {raw_height:.4f} -> scale factor {S:.6f}")

arm.scale = (S, S, S)
bpy.ops.object.select_all(action='DESELECT')
arm.select_set(True)
bpy.context.view_layer.objects.active = arm
bpy.ops.object.transform_apply(location=False, rotation=False, scale=True, properties=True)

mesh_ob.scale = (S, S, S)
bpy.ops.object.select_all(action='DESELECT')
mesh_ob.select_set(True)
bpy.context.view_layer.objects.active = mesh_ob
bpy.ops.object.transform_apply(location=False, rotation=False, scale=True, properties=True)
assert abs(mesh_ob.dimensions.z - TARGET_HEIGHT) < 0.05, \
    f"mesh height {mesh_ob.dimensions.z:.3f} != {TARGET_HEIGHT}"

n_loc = 0
for act in bpy.data.actions:
    for fc in act.fcurves:
        if fc.data_path.endswith('.location'):
            for kp in fc.keyframe_points:
                kp.co[1] *= S
            n_loc += 1
print(f"height normalized to {TARGET_HEIGHT} m; {n_loc} location fcurves scaled by {S:.6f}")

# ---- 4. rebuild materials as Principled with baked PBR textures -------------------
def load_image(name, colorspace):
    img = bpy.data.images.load(f"{TEX}/{name}", check_existing=True)
    img.colorspace_settings.name = colorspace
    return img

rebuilt = []
for mat in list(bpy.data.materials):
    mat_name = mat.name
    if mat_name not in ROUGHNESS:
        continue
    mat.use_nodes = True
    nt = mat.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    bsdf = nt.nodes.new("ShaderNodeBsdfPrincipled")
    out.location = (400, 0)
    bsdf.location = (100, 0)
    nt.links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])
    bsdf.inputs["Base Color"].default_value = (1.0, 1.0, 1.0, 1.0)
    bsdf.inputs["Roughness"].default_value = ROUGHNESS[mat_name]
    bsdf.inputs["Metallic"].default_value = 0.0
    bsdf.inputs["Specular"].default_value = 0.35
    # albedo (tinted) — Eyes has no texture, keeps plain near-black base color
    if mat_name != "Eyes":
        tex = nt.nodes.new("ShaderNodeTexImage")
        tex.location = (-400, 100)
        tex.image = load_image(f"tinted/{mat_name}_albedo.png", "sRGB")
        tex.interpolation = 'Smart'
        nt.links.new(tex.outputs["Color"], bsdf.inputs["Base Color"])
    # normal map
    if mat_name in NORMALS:
        nmap = nt.nodes.new("ShaderNodeNormalMap")
        nmap.location = (-400, -200)
        nmap.inputs["Strength"].default_value = 1.0
        ntex = nt.nodes.new("ShaderNodeTexImage")
        ntex.location = (-600, -300)
        ntex.image = load_image(NORMALS[mat_name], "Non-Color")
        ntex.interpolation = 'Smart'
        nt.links.new(ntex.outputs["Color"], nmap.inputs["Color"])
        nt.links.new(nmap.outputs["Normal"], bsdf.inputs["Normal"])
    rebuilt.append(mat_name)
print("MATERIALS REBUILT:", sorted(rebuilt))

# ---- 5. NLA wiring ----------------------------------------------------------------
actions = sorted(bpy.data.actions, key=lambda a: a.name.lower())
adt = arm.animation_data if arm.animation_data else arm.animation_data_create()
adt.action = None
for t in list(adt.nla_tracks):
    adt.nla_tracks.remove(t)
for act in actions:
    tr = adt.nla_tracks.new()
    tr.name = act.name
    tr.mute = False
    strip = tr.strips.new(act.name, int(act.frame_range[0]), act)
    strip.mute = False
print("NLA TRACKS:", [t.name for t in adt.nla_tracks])

# CRITICAL: node TRS in the exported glTF must equal the REST pose, NOT the
# evaluated NLA stack. Godot's importer drops "immutable" animation tracks
# (keys all equal to the node's stored TRS); with 11 overlapping unmuted NLA
# strips Blender would bake a blended pose into every bone node, making 92 of
# 93 pose channels look "immutable" and get silently discarded on import
# (leaving a T-pose body with one thumb track). Keeping scene evaluation at
# REST preserves them; the exporter still discovers + bakes every action.
adt.use_nla = False
adt.action = None
arm.data.pose_position = 'REST'
bpy.context.view_layer.update()

# ---- 3b. bake the armature deform INTO the mesh at REST -------------------------
# CRITICAL (v2 fix): the source mesh is authored in a T-pose while the rig's
# edit-rest is the idle stance. glTF stores IBM = inverse(rest), so an
# unbaked export ships T-pose vertices with idle binds -> identity skinning
# displays the raw T-pose on every renderer. Baking the armature modifier at
# REST writes idle-posed vertex data consistent with the binds; animations
# (whose keys are rig-space poses) then deform correctly everywhere.
# The source blend displays T-POSED at REST (its bind == edit-rest == idle,
# mesh raw == T-pose; it only looks posed while an action is active). So we
# must bake the deform UNDER THE IDLE ACTION, not at rest: apply the armature
# modifier while Man_Idle drives the armature -> idle-posed vertex data that
# is consistent with the idle binds the exporter writes.
arm.data.pose_position = 'POSE'
adt_bake = arm.animation_data if arm.animation_data else arm.animation_data_create()
adt_bake.use_nla = False
adt_bake.action = bpy.data.actions.get("Man_Idle")
bpy.context.view_layer.update()
bpy.ops.object.select_all(action='DESELECT')
mesh_ob.select_set(True)
bpy.context.view_layer.objects.active = mesh_ob
arm_mods = [m for m in mesh_ob.modifiers if m.type == 'ARMATURE']
if arm_mods:
    bpy.ops.object.modifier_apply(modifier=arm_mods[0].name)
    print("ARMATURE MODIFIER BAKED UNDER Man_Idle POSE — mesh matches binds")
else:
    print("WARN: no armature modifier found on BaseHuman")
adt_bake.action = None

# tidy: drop cameras/lights, purge orphans
for ob in list(bpy.data.objects):
    if ob.type in {'CAMERA', 'LIGHT'}:
        bpy.data.objects.remove(ob, do_unlink=True)
bpy.ops.outliner.orphans_purge(do_local_ids=True, do_recursive=True)

# ---- 6. export ---------------------------------------------------------------------
bpy.ops.export_scene.gltf(
    filepath=OUT,
    export_format='GLB',
    export_animation_mode='ACTIONS',
    export_animations=True,
    export_skins=True,
    export_yup=True,
    export_texcoords=True,
    export_normals=True,
    export_materials='EXPORT',
    export_extras=False,
    export_cameras=False,
    export_lights=False,
    export_def_bones=False,
    export_optimize_animation_size=False,  # Quaternius anims are pose-keyed; constant channels MUST survive
    export_anim_slide_to_zero=True,
    export_force_sampling=True,
    export_apply=False,
    export_image_format='AUTO',
)
print("EXPORTED:", OUT)
